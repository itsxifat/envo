export interface EndpointInfo {
  kind: 'ext' | 'web' | 'trunk';
  tenantId: number | null;
  extensionId?: number;
  number?: string;
  trunkId?: number;
  label: string;
}

export interface GeneratedConfig {
  files: Record<string, string>;
  endpoints: Map<string, EndpointInfo>;
  registrations: Map<string, { trunkId: number; tenantId: number | null }>;
  /** Number id -> tenant id (channel-limit groups are named did<id>). */
  numbers: Map<number, number>;
  warnings: string[];
}

const HEADER = '; Generated by Envo - DO NOT EDIT. Changes made here are overwritten on the next apply.\n';
const UNAVAILABLE = 'Goto(envo-unavailable,s,1)';
/** Labels a call as internal unless an inbound/outbound route already claimed it. */
const MARK_INTERNAL = 'ExecIf($["${CDR(direction)}" = ""]?Set(CDR(direction)=internal))';
const DAYS = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
const MONTHS = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];
const TZ_RE = /^[A-Za-z_]+(\/[A-Za-z0-9_+\-]+){0,2}$/;

export type RecordingPolicy = 'off' | 'inbound' | 'outbound' | 'all';

export function effectiveRecording(ext: Extension, tenant: Tenant): RecordingPolicy {
  return ext.recording === 'inherit' ? tenant.recording : ext.recording;
}

/** All forms a DID may arrive in: as entered, without "+", national and international. */
export function didVariants(num: string, countryCode: string, nationalPrefix: string): string[] {
  const out = new Set<string>([num]);
  const digits = num.replace(/^\+/, '');
  out.add(digits);
  if (countryCode && digits.startsWith(countryCode) && digits.length > countryCode.length + 4) {
    const national = digits.slice(countryCode.length);
    out.add(`+${digits}`);
    if (nationalPrefix !== undefined) out.add(`${nationalPrefix}${national}`);
  } else if (nationalPrefix && digits.startsWith(nationalPrefix) && countryCode) {
    const national = digits.slice(nationalPrefix.length);
    out.add(`${countryCode}${national}`);
    out.add(`+${countryCode}${national}`);
  }
  return [...out].filter((v) => /^\+?[0-9]{3,24}$/.test(v));
}

class Section {
  lines: string[] = [];
  constructor(name: string, comment?: string) {
    if (comment) this.lines.push(`; ${cfgText(comment, 120)}`);
    this.lines.push(`[${name}]`);
  }
  set(key: string, value: string | number | boolean | undefined | null): this {
    if (value === undefined || value === null || value === '') return this;
    this.lines.push(`${key}=${typeof value === 'boolean' ? (value ? 'yes' : 'no') : value}`);
    return this;
  }
  toString(): string {
    return this.lines.join('\n') + '\n';
  }
}

/** Dialplan builder for one context. */
class Ctx {
  lines: string[];
  constructor(name: string, comment?: string) {
    this.lines = [];
    if (comment) this.lines.push(`; ${cfgText(comment, 120)}`);
    this.lines.push(`[${name}]`);
  }
  exten(ext: string, apps: string[], labels: Record<number, string> = {}): this {
    apps.forEach((app, i) => {
      const label = labels[i] ? `(${labels[i]})` : '';
      if (i === 0) this.lines.push(`exten => ${ext},1${label},${app}`);
      else this.lines.push(` same => n${label},${app}`);
    });
    return this;
  }
  hint(ext: string, devices: string): this {
    this.lines.push(`exten => ${ext},hint,${devices}`);
    return this;
  }
  raw(line: string): this {
    this.lines.push(line);
    return this;
  }
  toString(): string {
    return this.lines.join('\n') + '\n';
  }
}

export function generate(model: Model): GeneratedConfig {
  const { settings } = model;
  const warnings: string[] = [];
  const endpoints = new Map<string, EndpointInfo>();
  const registrations = new Map<string, { trunkId: number; tenantId: number | null }>();

  const tenants = model.tenants.filter((t) => t.enabled);
  const tenantById = new Map(model.tenants.map((t) => [t.id, t]));
  const activeTenantIds = new Set(tenants.map((t) => t.id));
  const extensions = model.extensions.filter((e) => e.enabled && activeTenantIds.has(e.tenant_id));
  const extByKey = new Map(extensions.map((e) => [`${e.tenant_id}:${e.number}`, e]));
  const trunks = model.trunks.filter(
    (t) => t.enabled && (t.tenant_id === null || activeTenantIds.has(t.tenant_id)) && isHost(t.host),
  );
  const trunkById = new Map(trunks.map((t) => [t.id, t]));
  const soundById = new Map(model.sounds.map((s) => [s.id, s]));
  const byTenant = <T extends { tenant_id: number }>(rows: T[], tid: number) => rows.filter((r) => r.tenant_id === tid);

  const sound = (id: number | null, tid: number): string | null => {
    if (!id) return null;
    const s = soundById.get(id);
    if (!s || (s.tenant_id !== null && s.tenant_id !== tid)) return null;
    return soundPath(s);
  };

  /** Dialplan application that sends the call to a destination inside tenant `t`. */
  const dest = (t: Tenant, type: string, target: string): string => {
    const tid = t.id;
    switch (type) {
      case 'extension': {
        const e = extByKey.get(`${tid}:${target}`);
        return e ? `Goto(t${tid}-internal,${e.number},1)` : UNAVAILABLE;
      }
      case 'voicemail': {
        const e = extByKey.get(`${tid}:${target}`);
        return e && e.voicemail ? `Goto(t${tid}-vm,${e.number},1)` : UNAVAILABLE;
      }
      case 'ring_group':
        return model.ringGroups.some((r) => r.tenant_id === tid && String(r.id) === target)
          ? `Goto(t${tid}-rg-${Number(target)},s,1)`
          : UNAVAILABLE;
      case 'queue':
        return model.queues.some((q) => q.tenant_id === tid && String(q.id) === target)
          ? `Goto(t${tid}-q-${Number(target)},s,1)`
          : UNAVAILABLE;
      case 'ivr':
        return model.ivrs.some((i) => i.tenant_id === tid && String(i.id) === target)
          ? `Goto(t${tid}-ivr-${Number(target)},s,1)`
          : UNAVAILABLE;
      case 'time_condition':
        return model.timeConditions.some((c) => c.tenant_id === tid && String(c.id) === target)
          ? `Goto(t${tid}-tc-${Number(target)},s,1)`
          : UNAVAILABLE;
      case 'conference':
        return model.conferences.some((c) => c.tenant_id === tid && String(c.id) === target)
          ? `Goto(t${tid}-conf-${Number(target)},s,1)`
          : UNAVAILABLE;
      case 'external':
        return isPhoneNumber(target) ? `Goto(t${tid}-external,${target},1)` : UNAVAILABLE;
      case 'hangup':
        return 'Hangup()';
      default:
        return UNAVAILABLE;
    }
  };

  // ------------------------------------------------------------------ pjsip
  const pj: string[] = [HEADER];

  for (const t of tenants) {
    pj.push(`\n; ===== SIP server: ${cfgText(t.name)} (t${t.id}) =====\n`);
    for (const e of byTenant(extensions, t.id)) {
      if (!isSipUser(e.sip_username) || !isDigits(e.number, 2, 8)) {
        warnings.push(`Skipped extension ${e.number}: invalid username`);
        continue;
      }
      const policy = effectiveRecording(e, t);
      const vars = [
        `ENVO_TENANT=${t.id}`,
        `ENVO_EXT=${e.number}`,
        `ENVO_OUTBOUND=${e.allow_outbound ? 1 : 0}`,
        `ENVO_RECOUT=${policy === 'outbound' || policy === 'all' ? 1 : 0}`,
      ];
      const outCid = isPhoneNumber(e.outbound_cid) ? e.outbound_cid : '';
      if (outCid) vars.push(`ENVO_OUTCID=${outCid}`);
      const callerid = `"${cidName(e.name) || e.number}" <${e.number}>`;
      const mailbox = e.voicemail ? `${e.number}@t${t.id}` : undefined;

      const add = (name: string, web: boolean) => {
        const endpoint = new Section(name, `${e.number} ${e.name}${web ? ' (web phone)' : ''}`)
          .set('type', 'endpoint')
          .set('context', `t${t.id}-internal`)
          .set('subscribe_context', `t${t.id}-internal`)
          .set('disallow', 'all')
          .set('allow', web ? 'opus,g722,ulaw,alaw' : codecList(e.codecs, 'g722,ulaw,alaw,opus'))
          .set('auth', name)
          .set('aors', name)
          .set('callerid', callerid)
          .set('accountcode', `t${t.id}`)
          .set('language', /^[a-z]{2}(_[A-Z]{2})?$/.test(t.language) ? t.language : 'en')
          .set('mailboxes', mailbox)
          .set('identify_by', 'username')
          .set('dtmf_mode', 'rfc4733')
          .set('allow_subscribe', true)
          .set('send_pai', true)
          .set('trust_id_outbound', true)
          .set('named_call_group', `t${t.id}`)
          .set('named_pickup_group', `t${t.id}`)
          .set('direct_media', false)
          .set('device_state_busy_at', 0);
        // Browser phones reach Asterisk only through nginx's WebSocket proxy (127.0.0.1). Pin web
        // endpoints to it, and keep desk-phone credentials off that path, where fail2ban can't see
        // the real client address.
        if (web) {
          endpoint.set('webrtc', true).set('deny', '0.0.0.0/0.0.0.0').set('permit', '127.0.0.1/255.255.255.255');
        } else {
          endpoint.set('rtp_symmetric', true).set('force_rport', true).set('rewrite_contact', true).set('deny', '127.0.0.0/255.0.0.0');
        }
        for (const v of vars) endpoint.set('set_var', v);

        const auth = new Section(name)
          .set('type', 'auth')
          .set('auth_type', 'digest')
          .set('username', name)
          .set('password', cfgValue(web ? webPassword(e.sip_username) : e.sip_password));
        const aor = new Section(name)
          .set('type', 'aor')
          .set('max_contacts', web ? 5 : Math.min(Math.max(e.max_contacts, 1), 20))
          .set('remove_existing', true)
          .set('remove_unavailable', true)
          .set('qualify_frequency', web ? 30 : 60)
          .set('qualify_timeout', 3)
          .set('minimum_expiration', 60)
          .set('default_expiration', 300)
          .set('maximum_expiration', 3600);
        pj.push(endpoint.toString(), auth.toString(), aor.toString());
        endpoints.set(name, {
          kind: web ? 'web' : 'ext',
          tenantId: t.id,
          extensionId: e.id,
          number: e.number,
          label: e.name,
        });
      };
      add(e.sip_username, false);
      if (e.webrtc) add(webEndpoint(e), true);
    }
  }

  pj.push('\n; ===== Trunks =====\n');
  for (const tr of trunks) {
    const ep = trunkEndpoint(tr);
    const transport = `transport-${tr.transport}`;
    const tparam = tr.transport === 'udp' ? '' : `;transport=${tr.transport}`;
    const target = `${tr.host}:${tr.port}`;
    const hasAuth = tr.auth_mode !== 'ip' && tr.password !== '' && isSipUser(tr.auth_username || tr.username);
    const fromUser = isSipUser(tr.from_user) ? tr.from_user : tr.auth_mode === 'register' && isSipUser(tr.username) ? tr.username : '';
    const fromDomain = isHost(tr.from_domain) ? tr.from_domain : tr.auth_mode === 'register' ? tr.host : '';
    const proxy = tr.outbound_proxy && isHost(tr.outbound_proxy.replace(/:\d+$/, ''))
      ? `sip:${tr.outbound_proxy}\\;lr`
      : undefined;

    const endpoint = new Section(ep, `Trunk ${tr.name}`)
      .set('type', 'endpoint')
      .set('transport', transport)
      .set('context', 'envo-from-trunk')
      .set('disallow', 'all')
      .set('allow', codecList(tr.codecs, 'alaw,ulaw,g722'))
      .set('aors', ep)
      .set('outbound_auth', hasAuth ? `${ep}_auth` : undefined)
      .set('from_user', fromUser)
      .set('from_domain', fromDomain)
      .set('identify_by', 'ip')
      .set('direct_media', false)
      .set('rtp_symmetric', true)
      .set('force_rport', true)
      .set('rewrite_contact', true)
      .set('dtmf_mode', tr.dtmf_mode)
      .set('send_pai', tr.send_pai)
      .set('trust_id_inbound', true)
      .set('accountcode', tr.tenant_id ? `t${tr.tenant_id}` : undefined)
      .set('outbound_proxy', proxy)
      .set('set_var', `ENVO_TRUNK_ID=${tr.id}`)
      .set('set_var', `ENVO_TRUNK_MAX=${tr.max_channels}`);
    pj.push(endpoint.toString());

    if (hasAuth) {
      pj.push(
        new Section(`${ep}_auth`)
          .set('type', 'auth')
          .set('auth_type', 'digest')
          .set('username', tr.auth_username || tr.username)
          .set('password', cfgValue(tr.password))
          .toString(),
      );
    }

    pj.push(
      new Section(ep)
        .set('type', 'aor')
        .set('contact', `sip:${target}${tparam}`)
        .set('qualify_frequency', tr.qualify ? 60 : 0)
        .set('qualify_timeout', 3)
        .toString(),
    );

    if (tr.auth_mode === 'register' && hasAuth && isSipUser(tr.username)) {
      const contactUser = isSipUser(tr.contact_user) ? tr.contact_user : tr.username;
      pj.push(
        new Section(ep)
          .set('type', 'registration')
          .set('transport', transport)
          .set('outbound_auth', `${ep}_auth`)
          .set('server_uri', `sip:${target}${tparam}`)
          .set('client_uri', `sip:${tr.username}@${fromDomain || tr.host}${tr.port !== 5060 && !fromDomain ? `:${tr.port}` : ''}`)
          .set('contact_user', contactUser)
          .set('expiration', tr.register_expiry)
          .set('retry_interval', 30)
          .set('forbidden_retry_interval', 300)
          .set('fatal_retry_interval', 300)
          .set('max_retries', 100000)
          .set('auth_rejection_permanent', false)
          .set('line', true)
          .set('endpoint', ep)
          .set('outbound_proxy', proxy)
          .toString(),
      );
      registrations.set(ep, { trunkId: tr.id, tenantId: tr.tenant_id });
    }

    // The provider host is often repeated in "extra provider IPs"; list each address once.
    const matches = [...new Set([tr.host, ...tr.match_ips.split(/[\s,]+/).filter((v) => v && isIpOrCidr(v))])];
    const identify = new Section(ep).set('type', 'identify').set('endpoint', ep);
    for (const m of matches) identify.set('match', m);
    pj.push(identify.toString());

    endpoints.set(ep, { kind: 'trunk', tenantId: tr.tenant_id, trunkId: tr.id, label: tr.name });
  }

  // -------------------------------------------------------------- dialplan
  const dp: string[] = [HEADER];
  const { country_code: cc, national_prefix: np } = settings;

  // Inbound caller blocklist checks, placed before channel limits so rejected calls use none.
  const blockChecks = (tid: number): string[] => {
    const entries = model.blocked.filter((b) => b.tenant_id === tid);
    const checks: string[] = [];
    if (entries.some((b) => b.match !== 'anonymous')) {
      checks.push(`GotoIf(\${DIALPLAN_EXISTS(t${tid}-block,\${FILTER(0-9+,\${CALLERID(num)})},1)}?envo-blocked,s,1)`);
    }
    if (entries.some((b) => b.match === 'anonymous')) {
      checks.push('GotoIf($[${LEN(${FILTER(0-9,${CALLERID(num)})})} = 0]?envo-blocked,s,1)');
    }
    return checks;
  };

  // DIDs
  const didCtx = new Ctx('envo-did', 'Inbound numbers (DIDs)');
  const seenDid = new Set<string>();
  for (const n of model.numbers) {
    const t = tenantById.get(n.tenant_id);
    if (!n.enabled || !t || !t.enabled || !isPhoneNumber(n.number)) continue;
    const record = n.recording === 'on' || (n.recording === 'inherit' && (t.recording === 'inbound' || t.recording === 'all'));
    const prefix = cidName(n.cid_prefix);
    for (const variant of didVariants(n.number, cc, np)) {
      if (seenDid.has(variant)) continue;
      seenDid.add(variant);
      // The arriving trunk's own channel limit was already applied in envo-inbound.
      const apps = [
        `NoOp(Envo DID ${n.number} for SIP server ${t.slug})`,
        `Set(__ENVO_TENANT=${t.id})`,
        `Set(__ENVO_DID=${n.number})`,
        `Set(CHANNEL(accountcode)=t${t.id})`,
        `Set(CDR(did)=${n.number})`,
        ...blockChecks(t.id),
        `Gosub(envo-limit,s,1(envo_did,did${n.id},${n.max_channels}))`,
        `GotoIf($[\${ENVO_LIMIT_OK} = 0]?envo-busy,s,1)`,
        `Gosub(envo-limit,s,1(envo_tenant,t${t.id},${t.max_channels}))`,
        `GotoIf($[\${ENVO_LIMIT_OK} = 0]?envo-busy,s,1)`,
      ];
      if (prefix) apps.push(`Set(CALLERID(name)=${prefix} \${CALLERID(name)})`);
      if (record) apps.push('Set(__ENVO_REC=1)');
      apps.push(dest(t, n.dest_type, n.dest_target));
      didCtx.exten(variant, apps);
    }
  }
  dp.push(didCtx.toString());

  // Trunk catch-all destinations
  const tdCtx = new Ctx('envo-trunk-default', 'Calls from a trunk that match no number');
  for (const tr of trunks) {
    if (!tr.tenant_id || tr.default_dest_type === 'hangup') continue;
    const t = tenantById.get(tr.tenant_id);
    if (!t) continue;
    tdCtx.exten(`trunk${tr.id}`, [
      `Set(__ENVO_TENANT=${t.id})`,
      `Set(CHANNEL(accountcode)=t${t.id})`,
      ...blockChecks(t.id),
      `Gosub(envo-limit,s,1(envo_tenant,t${t.id},${t.max_channels}))`,
      `GotoIf($[\${ENVO_LIMIT_OK} = 0]?envo-busy,s,1)`,
      dest(t, tr.default_dest_type, tr.default_dest_target),
    ]);
  }
  dp.push(tdCtx.toString());

  for (const t of tenants) {
    const tid = t.id;
    const exts = byTenant(extensions, tid);
    const internal = new Ctx(`t${tid}-internal`, `SIP server ${t.name}: internal calls`);

    for (const e of exts) {
      if (!isSipUser(e.sip_username)) continue;
      const policy = effectiveRecording(e, t);
      const recordIn = policy === 'inbound' || policy === 'all' ? 1 : 0;
      const web = e.webrtc ? webEndpoint(e) : '';
      internal.exten(e.number, [
        `Gosub(envo-dial-ext,s,1(${tid},${e.number},${e.ring_timeout},${e.voicemail ? 1 : 0},${recordIn},${e.sip_username},${web}))`,
        'Hangup()',
      ]);
      internal.hint(e.number, web ? `PJSIP/${e.sip_username}&PJSIP/${web}` : `PJSIP/${e.sip_username}`);
    }

    // Group numbers jump into an "s" context, so remember what the caller dialed for the call log.
    const numbered: Array<[string, string]> = [
      ...byTenant(model.ringGroups, tid).map((rg): [string, string] => [rg.number, `t${tid}-rg-${rg.id}`]),
      ...byTenant(model.queues, tid).map((q): [string, string] => [q.number, `t${tid}-q-${q.id}`]),
      ...byTenant(model.ivrs, tid).map((ivr): [string, string] => [ivr.number, `t${tid}-ivr-${ivr.id}`]),
      ...byTenant(model.conferences, tid).map((c): [string, string] => [c.number, `t${tid}-conf-${c.id}`]),
    ];
    for (const [number, context] of numbered) {
      if (isDigits(number, 2, 8)) internal.exten(number, [MARK_INTERNAL, 'Set(CDR(dialed)=${EXTEN})', `Goto(${context},s,1)`]);
    }

    // Feature codes
    internal
      .raw('; Feature codes')
      .exten('*43', [MARK_INTERNAL, 'Answer()', 'Wait(0.5)', 'Playback(demo-echotest)', 'Echo()', 'Playback(demo-echodone)', 'Hangup()'])
      .exten('*97', [MARK_INTERNAL, 'Answer()', 'Wait(0.5)', `VoiceMailMain(\${ENVO_EXT}@t${tid},s)`, 'Hangup()'])
      .exten('*98', [MARK_INTERNAL, 'Answer()', 'Wait(0.5)', `VoiceMailMain(@t${tid})`, 'Hangup()'])
      .exten('*65', [MARK_INTERNAL, 'Answer()', 'Wait(0.5)', 'SayDigits(${ENVO_EXT})', 'Hangup()'])
      .exten('*60', [MARK_INTERNAL, 'Answer()', 'Wait(0.5)', `SayUnixTime(,${TZ_RE.test(t.timezone) ? t.timezone : 'UTC'},IMp)`, 'Hangup()'])
      .exten('*78', [MARK_INTERNAL, `Gosub(envo-feature,s,1(${tid},dnd,1))`])
      .exten('*79', [MARK_INTERNAL, `Gosub(envo-feature,s,1(${tid},dnd,))`])
      .exten('_*72.', [MARK_INTERNAL, `Gosub(envo-feature,s,1(${tid},cfu,\${EXTEN:3}))`])
      .exten('*73', [MARK_INTERNAL, `Gosub(envo-feature,s,1(${tid},cfu,))`])
      .exten('*8', [MARK_INTERNAL, 'Pickup()', 'Hangup()'])
      .raw(`include => t${tid}-outbound`);
    dp.push(internal.toString());

    // Outbound routes
    const outbound = new Ctx(`t${tid}-outbound`, `SIP server ${t.name}: outbound routes`);
    const seenPattern = new Set<string>();
    for (const r of byTenant(model.routes, tid).filter((r) => r.enabled)) {
      const routeTrunks = r.trunk_ids
        .map((id) => trunkById.get(id))
        .filter((tr): tr is Trunk => !!tr && (tr.tenant_id === null || tr.tenant_id === tid));
      const cid = isPhoneNumber(r.callerid) ? r.callerid : isPhoneNumber(t.outbound_cid) ? t.outbound_cid : '';
      const prepend = /^\+?[0-9]{0,15}$/.test(r.prepend) ? r.prepend : '';
      for (const p of r.patterns) {
        if (!isDialPattern(p)) {
          warnings.push(`Route ${r.name}: invalid pattern ${p}`);
          continue;
        }
        const pattern = toDialplanPattern(p);
        if (seenPattern.has(pattern)) continue;
        seenPattern.add(pattern);
        if (routeTrunks.length === 0) {
          outbound.exten(pattern, [`NoOp(Envo route ${cfgText(r.name)} has no usable trunk)`, UNAVAILABLE]);
          continue;
        }
        const apps = [
          `NoOp(Envo route ${cfgText(r.name)})`,
          `Gosub(envo-out-pre,s,1(${tid},${t.max_channels},${cid}))`,
          `GotoIf($[\${ENVO_OUT_OK} = 0]?envo-unavailable,s,1)`,
          `Set(ENVO_NUM=${prepend}\${EXTEN:${r.strip}})`,
        ];
        routeTrunks.forEach((tr, i) => {
          if (i > 0) {
            apps.push(`GotoIf($["\${ENVO_DIALSTATUS}" != "CHANUNAVAIL" & "\${ENVO_DIALSTATUS}" != "CONGESTION"]?done)`);
          }
          apps.push(`Gosub(envo-dial-trunk,s,1(${trunkEndpoint(tr)},\${ENVO_NUM},${tr.id},${tr.max_channels}))`);
        });
        apps.push('Hangup()');
        outbound.exten(pattern, apps, { [apps.length - 1]: 'done' });
      }
    }
    dp.push(outbound.toString());

    // External destinations (call forwarding / follow-me to a phone number)
    dp.push(
      new Ctx(`t${tid}-external`)
        .exten('_[+0-9].', [`GotoIf(\${DIALPLAN_EXISTS(t${tid}-outbound,\${EXTEN},1)}?t${tid}-outbound,\${EXTEN},1)`, UNAVAILABLE])
        .toString(),
    );

    // Voicemail drop
    const vm = new Ctx(`t${tid}-vm`);
    for (const e of exts.filter((x) => x.voicemail)) {
      vm.exten(e.number, ['Answer()', 'Wait(0.5)', `VoiceMail(${e.number}@t${tid},u)`, 'Hangup()']);
    }
    dp.push(vm.toString());

    // Member legs used by ring groups and queues (respects DND, rings every device)
    const qm = new Ctx(`t${tid}-qm`);
    for (const e of exts) {
      const web = e.webrtc ? webEndpoint(e) : '';
      qm.exten(
        e.number,
        [
          `GotoIf($["\${DB(envo/t${tid}/${e.number}/dnd)}" = "1"]?busy)`,
          `Gosub(envo-ds,s,1(${e.sip_username},${web}))`,
          `GotoIf($[\${LEN(\${ENVO_DS})} = 0]?busy)`,
          'Dial(${ENVO_DS},,tT)',
          'Hangup(17)',
        ],
        { 4: 'busy' },
      );
    }
    dp.push(qm.toString());

    // Ring groups
    for (const rg of byTenant(model.ringGroups, tid)) {
      const members = rg.members.filter((m) => extByKey.has(`${tid}:${m}`));
      const ctx = new Ctx(`t${tid}-rg-${rg.id}`, `Ring group ${rg.name}`);
      const apps = [
        `NoOp(Envo ring group ${cfgText(rg.name)})`,
        'ExecIf($["${CDR(direction)}" = ""]?Set(CDR(direction)=internal))',
      ];
      const prefix = cidName(rg.cid_prefix);
      if (prefix) apps.push(`Set(CALLERID(name)=${prefix} \${CALLERID(name)})`);
      apps.push('GosubIf($["${ENVO_RECOUT}" = "1" | "${ENVO_REC}" = "1"]?envo-record,s,1)');
      if (members.length) {
        if (rg.strategy === 'hunt') {
          for (const m of members) apps.push(`Dial(Local/${m}@t${tid}-qm,${rg.ring_time},tT)`);
        } else {
          apps.push(`Dial(${members.map((m) => `Local/${m}@t${tid}-qm`).join('&')},${rg.ring_time},tT)`);
        }
      }
      apps.push(dest(t, rg.failover_dest_type, rg.failover_dest_target));
      ctx.exten('s', apps);
      dp.push(ctx.toString());
    }

    // Queues
    for (const q of byTenant(model.queues, tid)) {
      const ctx = new Ctx(`t${tid}-q-${q.id}`, `Queue ${q.name}`);
      const apps = [
        `NoOp(Envo queue ${cfgText(q.name)})`,
        'ExecIf($["${CDR(direction)}" = ""]?Set(CDR(direction)=internal))',
        'Answer()',
        'GosubIf($["${ENVO_RECOUT}" = "1" | "${ENVO_REC}" = "1"]?envo-record,s,1)',
      ];
      const join = sound(q.join_sound_id, tid);
      if (join) apps.push(`Playback(${join})`);
      apps.push(`Queue(t${tid}-q${q.id},t,,,${q.max_wait > 0 ? q.max_wait : ''})`);
      apps.push(dest(t, q.failover_dest_type, q.failover_dest_target));
      ctx.exten('s', apps);
      dp.push(ctx.toString());
    }

    // IVRs
    for (const ivr of byTenant(model.ivrs, tid)) {
      const ctx = new Ctx(`t${tid}-ivr-${ivr.id}`, `IVR ${ivr.name}`);
      const greeting = sound(ivr.greeting_sound_id, tid) ?? 'silence/1';
      ctx.exten(
        's',
        [
          `NoOp(Envo IVR ${cfgText(ivr.name)})`,
          'Set(ENVO_IVR_TRIES=0)',
          'ExecIf($["${CDR(direction)}" = ""]?Set(CDR(direction)=internal))',
          'Answer()',
          'Wait(1)',
          'Set(TIMEOUT(digit)=3)',
          `Set(TIMEOUT(response)=${ivr.timeout})`,
          `Background(${greeting})`,
          `WaitExten(${ivr.timeout})`,
        ],
        { 5: 'menu' },
      );
      const used = new Set<string>();
      for (const opt of ivr.options) {
        if (!/^[0-9*#]$/.test(opt.digit) || used.has(opt.digit)) continue;
        used.add(opt.digit);
        ctx.exten(opt.digit, [dest(t, opt.dest_type, opt.dest_target)]);
      }
      if (ivr.direct_dial) {
        for (const e of exts) if (!used.has(e.number)) ctx.exten(e.number, [`Goto(t${tid}-internal,${e.number},1)`]);
      }
      const retry = (final: string) => [
        'Set(ENVO_IVR_TRIES=$[${ENVO_IVR_TRIES} + 1])',
        `GotoIf($[\${ENVO_IVR_TRIES} < ${ivr.max_retries}]?s,menu)`,
        final,
      ];
      ctx.exten('t', retry(dest(t, ivr.timeout_dest_type, ivr.timeout_dest_target)));
      ctx.exten('i', ['Playback(option-is-invalid)', ...retry(dest(t, ivr.invalid_dest_type, ivr.invalid_dest_target))]);
      dp.push(ctx.toString());
    }

    // Time conditions
    const tz = TZ_RE.test(t.timezone) ? t.timezone : 'UTC';
    for (const tc of byTenant(model.timeConditions, tid)) {
      const ctx = new Ctx(`t${tid}-tc-${tc.id}`, `Time condition ${tc.name}`);
      const apps = [`NoOp(Envo time condition ${cfgText(tc.name)} mode=${tc.mode})`];
      if (tc.mode === 'open') apps.push('Goto(match)');
      else if (tc.mode === 'closed') apps.push('Goto(nomatch)');
      else {
        for (const h of tc.holidays ?? []) {
          const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(h.date);
          if (!m) continue;
          const month = MONTHS[Number(m[2]) - 1];
          if (!month) continue;
          apps.push(`GotoIfTime(*,*,${Number(m[3])},${month},${tz}?nomatch)`);
        }
        for (const rule of tc.rules ?? []) {
          const days = (rule.days ?? []).filter((d) => DAYS.includes(d));
          const range = timeRange(rule.start, rule.end);
          if (!days.length || !range) continue;
          apps.push(`GotoIfTime(${range},${days.join('&')},*,*,${tz}?match)`);
        }
        apps.push('Goto(nomatch)');
      }
      const matchIndex = apps.length;
      apps.push(dest(t, tc.match_dest_type, tc.match_dest_target));
      apps.push(dest(t, tc.nomatch_dest_type, tc.nomatch_dest_target));
      ctx.exten('s', apps, { [matchIndex]: 'match', [matchIndex + 1]: 'nomatch' });
      dp.push(ctx.toString());
    }

    // Blocked callers: only looked up with DIALPLAN_EXISTS, never executed.
    const block = new Ctx(`t${tid}-block`, 'Blocked caller IDs');
    const blockKeys = new Set<string>();
    const addBlock = (key: string) => {
      if (blockKeys.has(key)) return;
      blockKeys.add(key);
      block.exten(key, ['NoOp(blocked)']);
    };
    for (const b of byTenant(model.blocked, tid)) {
      if (b.match === 'exact' && isPhoneNumber(b.number)) didVariants(b.number, cc, np).forEach(addBlock);
      else if (b.match === 'prefix' && /^\+?[0-9]{1,15}$/.test(b.number)) prefixVariants(b.number, cc, np).forEach((v) => addBlock(`_${v}.`));
    }
    dp.push(block.toString());

    // Conference rooms
    for (const c of byTenant(model.conferences, tid)) {
      const ctx = new Ctx(`t${tid}-conf-${c.id}`, `Conference ${c.name}`);
      const apps = [
        `NoOp(Envo conference ${cfgText(c.name)})`,
        'ExecIf($["${CDR(direction)}" = ""]?Set(CDR(direction)=internal))',
        'Answer()',
        'Wait(0.5)',
      ];
      if (/^[0-9]{1,10}$/.test(c.pin)) apps.push(`Authenticate(${c.pin})`);
      apps.push(`Set(CONFBRIDGE(bridge,max_members)=${Math.min(Math.max(c.max_members, 2), 200)})`);
      apps.push('Set(CONFBRIDGE(user,music_on_hold_when_empty)=yes)');
      if (c.announce_join) apps.push('Set(CONFBRIDGE(user,announce_user_count)=yes)');
      apps.push(`ConfBridge(t${tid}-conf${c.id})`, 'Hangup()');
      ctx.exten('s', apps);
      dp.push(ctx.toString());
    }
  }

  // -------------------------------------------------------------- voicemail
  const vmc: string[] = [HEADER];
  for (const t of tenants) {
    const boxes = byTenant(extensions, t.id).filter((e) => e.voicemail);
    vmc.push(`[t${t.id}]`);
    for (const e of boxes) {
      const pin = isDigits(e.voicemail_pin, 4, 10) ? e.voicemail_pin : '0000';
      const email = /^[^\s@,|;]+@[^\s@,|;]+\.[a-zA-Z]{2,}$/.test(e.email) ? e.email : '';
      vmc.push(`${e.number} => ${pin},${cfgText(e.name, 40) || e.number},${email},,attach=yes|delete=no`);
    }
    vmc.push('');
  }

  // -------------------------------------------------------------- queues
  const qc: string[] = [HEADER];
  for (const t of tenants) {
    for (const q of byTenant(model.queues, t.id)) {
      const s = new Section(`t${t.id}-q${q.id}`, `Queue ${q.name}`)
        .set('strategy', q.strategy)
        .set('timeout', q.agent_timeout)
        .set('retry', 3)
        .set('wrapuptime', q.wrapup)
        .set('maxlen', 0)
        .set('joinempty', 'unavailable,invalid,unknown')
        .set('leavewhenempty', 'unavailable,invalid,unknown')
        .set('announce-position', q.announce_position ? 'yes' : 'no')
        .set('announce-frequency', q.announce_position ? 45 : 0)
        .set('musicclass', 'default')
        .set('ringinuse', false)
        .set('setinterfacevar', true)
        .set('setqueuevar', true);
      for (const m of q.members) {
        const e = extByKey.get(`${t.id}:${m}`);
        if (!e) continue;
        s.set('member', `Local/${e.number}@t${t.id}-qm,0,${cfgText(e.name, 40) || e.number},hint:${e.number}@t${t.id}-internal`);
      }
      qc.push(s.toString());
    }
  }

  return {
    files: {
      'pjsip_envo.conf': pj.join('\n'),
      'extensions_envo_lib.conf': libConf,
      'extensions_envo.conf': dp.join('\n'),
      'voicemail_envo.conf': vmc.join('\n'),
      'queues_envo.conf': qc.join('\n'),
    },
    endpoints,
    registrations,
    numbers: new Map(model.numbers.map((n) => [n.id, n.tenant_id])),
    warnings,
  };
}

/** A caller-ID prefix in national, international and +international form ("017" -> 88017, +88017). */
export function prefixVariants(prefix: string, countryCode: string, nationalPrefix: string): string[] {
  const out = new Set<string>([prefix]);
  const digits = prefix.replace(/^\+/, '');
  out.add(digits);
  if (countryCode && digits.startsWith(countryCode)) {
    out.add(`+${digits}`);
    const rest = digits.slice(countryCode.length);
    if (rest) out.add(`${nationalPrefix}${rest}`);
  } else if (nationalPrefix && digits.startsWith(nationalPrefix) && countryCode) {
    const rest = digits.slice(nationalPrefix.length);
    out.add(`${countryCode}${rest}`);
    out.add(`+${countryCode}${rest}`);
  }
  return [...out].filter((v) => /^\+?[0-9]{1,20}$/.test(v));
}

/** "09:00" + "18:00" -> "09:00-17:59" (GotoIfTime ranges are inclusive). */
function timeRange(start: string, end: string): string | null {
  const s = /^(\d{2}):(\d{2})$/.exec(start);
  const e = /^(\d{2}):(\d{2})$/.exec(end);
  if (!s || !e) return null;
  const sm = Number(s[1]) * 60 + Number(s[2]);
  let em = Number(e[1]) * 60 + Number(e[2]) - 1;
  if (sm > 1439 || em > 1439) return null;
  if (em < 0) em = 1439;
  const fmt = (m: number) => `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`;
  return `${fmt(sm)}-${fmt(em)}`;
}
